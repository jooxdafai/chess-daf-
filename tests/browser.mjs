// Run with CHESS_PLAYWRIGHT_MODULE pointing to an installed playwright module.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.CHESS_PLAYWRIGHT_MODULE || '@playwright/test');
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1100},extraHTTPHeaders:{'X-Chess-User':'owner'}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.CHESS_TEST_URL || 'http://127.0.0.1:18972/');
let releaseCreate;
const createGate=new Promise(resolve=>{releaseCreate=resolve;});
await page.route('**/api/games',async route=>{if(route.request().method()==='POST')await createGate;await route.continue();});
await page.getByRole('button',{name:'ابدأ ماتش'}).click();
assert.equal(await page.locator('#board [data-square="e2"]').isDisabled(),true,'board must wait for game creation instead of silently dropping an early move');
releaseCreate();
await page.locator('#board [data-square="e2"]').click();
await page.unroute('**/api/games');
await page.locator('#board [data-square="e4"]').click();
await page.waitForFunction(()=>document.querySelectorAll('.move-row').length===1 && !document.querySelector('.move-row')?.textContent.includes('—'));
await page.reload();
await page.waitForFunction(()=>document.querySelector('.move-row')?.textContent.includes('e4'));
await page.locator('#hint').click();
await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('تحليل سريع'));
page.on('dialog',d=>d.accept());
await page.locator('#resign').click();
await page.locator('#show-best').waitFor();
await page.locator('#show-best').click();
await page.getByRole('button',{name:'تدرّب',exact:true}).click();
await page.locator('[data-puzzle="starter-capture"]').click();
await page.locator('#practice-board [data-square="d2"]').click();
await page.locator('#practice-board [data-square="e3"]').click();
await page.waitForFunction(()=>document.querySelector('#practice-feedback')?.textContent.includes('صح'));
await page.reload();
await page.getByRole('button',{name:'تدرّب',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#solved-count')?.textContent==='1');
await page.getByRole('button',{name:'العب',exact:true}).click();
await page.screenshot({path:'/tmp/chess-daf-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'/tmp/chess-daf-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile must not overflow horizontally');
assert.deepEqual(errors,[]);
await page.locator('#new-game').click();
await page.waitForFunction(()=>document.querySelector('#game-status').textContent.includes('دور الأبيض'));
assert.equal(await page.locator('.review-eyebrow').count(),0,'new game must clear the previous review lesson');
await page.locator('#resign').click();
await page.locator('#color').selectOption('black');
await page.locator('#mode').selectOption('match');
await page.locator('[data-time="60"]').click();
await page.locator('#new-game').click();
await page.waitForFunction(()=>document.querySelector('#game-status').textContent.includes('دور الأسود'));
assert.equal(await page.locator('#hint').isDisabled(),true,'match mode must not offer hints');
assert.equal(await page.locator('#board .square').first().getAttribute('data-square'),'h1','black board must face black');
assert.match(await page.locator('#my-clock').textContent(),/^(0:[0-5][0-9]|1:00)$/);
await page.locator('#resign').click();
console.log('PASS: play, bot reply, reload, hint, resign, review, best alternative, exercise, persisted progress, desktop/mobile layout; no page errors.');
await browser.close();
